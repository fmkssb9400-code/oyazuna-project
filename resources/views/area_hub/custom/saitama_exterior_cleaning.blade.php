<h2>発注までの段取り</h2>
<p>初めて業者を探すという担当者の方も少なくないでしょう。細かい流れは業者によって違いますが、大枠は次のように進みます。</p>
<ul>
<li>問い合わせ・現地調査の依頼</li>
<li>現地調査(建物の状態・屋上の設備・汚れの度合いをチェック。無料としている業者が大半)</li>
<li>見積書の受領(工法・日数・費用が明記されているか確認)</li>
<li>契約、そして施工へ。夏場に依頼する場合は、猛暑を踏まえた作業時間の調整が入ることもある</li>
<li>仕上がりを確認して支払い</li>
</ul>

<h2>比較する際に見落としたくないこと</h2>
<p>1社の話だけで決めるのは避け、3〜5社程度から話を聞くのが基本です。金額の大小だけでなく、次のような観点も突き合わせてみてください。</p>
<ul>
<li>㎡単価なのか一式料金なのか、内訳が明確か</li>
<li>なぜその工法(ロープアクセス・ゴンドラ・足場)を勧めているのか、理由に納得できるか</li>
<li>労災保険・損害賠償責任保険に加入しているか</li>
<li>保証期間はどれくらいか、仕上がりに不満があった場合はどう対応してもらえるか</li>
</ul>

