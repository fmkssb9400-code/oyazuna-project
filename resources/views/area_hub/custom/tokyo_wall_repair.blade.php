<h2>東京都で外壁補修を検討している方へ</h2>
<p>「法定点検でタイルの浮きを指摘されたが、大掛かりな足場工事は避けたい」「ひび割れを見つけたが、どの工法で直せばいいのか分からない」。東京都内でビルやマンションを所有・管理していると、こうした悩みに直面してはいませんか。</p>
<p>東京都内は建築基準法12条点検の対象となる特定建築物が多く、竣工や前回の外壁改修から10年を超えたタイミングで実施が義務付けられている外壁の全面打診調査で「タイルの浮き」や「ひび割れ」を指摘され、そこから補修工事の発注に至るケースが典型的な流れです。この記事では、費用相場から補助金の実態、業者選びの注意点までまとめました。</p>

<h2>東京都内の外壁補修、補助金は使えるのか</h2>
<p>調べてみると、東京都23区の7割超・23区外の7市で、外壁塗装や屋根塗装に関連する何らかの補助金制度があるとされています(複数の専門業者サイトの横断調査による)。ただし、ここは正確にお伝えする必要があります。</p>
<div style="margin: 2em 0; padding: 16px 20px; background-color: #fff7ed; border: 2px solid #d97706;"><div style="display: inline-block; margin-bottom: 10px; padding: 4px 14px; background-color: #d97706; color: #ffffff; font-weight: bold;">誤解しやすいポイント</div><div>調べた制度の多くは「遮熱塗装」「断熱改修」といった省エネ目的の工事を対象にしたもので、ひび割れ補修やタイルの浮き補修といった一般的な「外壁補修」そのものを直接対象にした補助金は限定的です。また戸建て住宅や分譲マンションの個人区分所有者向けの制度が中心で、ビルオーナーが対象になるかは制度ごとに確認が必要です。区市町村ごとに内容・予算上限が異なり、年度が変われば内容も変わるため、「うちの区にも補助金があるはず」と決めつけず、着工前に必ずお住まいの区市町村の窓口で対象工事の範囲を確認することをおすすめします。</div></div>

<h2>費用相場</h2>
<p>外壁補修は工事内容によって単価が大きく異なります。タイル関連の補修を例にすると、目安は次のとおりです。</p>
<ul>
<li>タイル工事全体：1㎡あたり1万円〜5万円(下地処理5,000〜6,000円、タイル張替え8,000〜10,000円、足場費700〜1,000円、タイル塗装2,000〜2,500円が目安の内訳)</li>
<li>タイル張替え：タイル・目地材込みで1㎡あたり15,000〜25,000円、全体工事では23,000〜35,000円/㎡が一般的</li>
<li>小規模補修(1〜5枚程度のタイル交換)：工賃込みで20,000〜22,000円程度</li>
</ul>
<p>価格は地域・業者・タイルの種類・施工方法・下地の劣化状態によって大きく変動するため、相見積もりを取ることが実質的に必須とされています。</p>

<h2>ひび割れ・浮きの症状に応じた工法</h2>
<p>外壁補修にはひび割れの幅や症状によって、いくつかの工法があります。</p>
<ul>
<li><strong>シール工法(被覆工法)</strong>：ひび割れ幅0.2〜0.3mm未満の軽微な収縮ひび割れが対象。エポキシ樹脂等でひび割れ表面を被覆します。</li>
<li><strong>エポキシ樹脂注入工法</strong>：細かく深いひび割れに樹脂を注入する工法です。</li>
<li><strong>Uカットシール材充填工法</strong>：ひび割れ幅0.5〜1.0mm以上の比較的大きいひび割れが対象で、鋼材が腐食していない場合に適用します。</li>
<li><strong>アンカーピンニング工法</strong>：ひび割れ用ではなく、モルタルやタイルの「浮き」を固定する工法です。浮いた部分にピンを打ち込み、エポキシ樹脂を注入して躯体に固定します。</li>
</ul>
<p>工法選定の基準(ひび割れ幅の区切り方など)は業者・団体によって幅があり、統一基準というより各社の目安という位置づけです。どの工法が適しているかは、現地調査で症状を確認したうえで業者に判断してもらうのが確実です。</p>

<h2>足場を組まない外壁補修という選択肢</h2>
<p>部分的なクラック補修や数枚程度のタイルの浮きなど、範囲が限定的な補修であれば、屋上からロープを垂らして作業するロープアクセス(無足場工法)でも対応できるケースがあります。コスト・工期を圧縮でき、法定点検で急に指摘を受けた場合の緊急対応にも向いています。費用相場や工法選定について詳しくは、当サイトの別記事「<a href="/news/wall-repair-cost-no-scaffold">外壁補修の費用相場は？足場が組めない狭小地・ビルは無足場工法という選択肢も</a>」でも解説していますので、あわせてご確認ください。</p>

<h2>発注の流れ</h2>
<p>初めて外壁補修を発注する場合、流れが見えないと不安に感じるものです。業者による違いはありますが、おおむね次のように進みます。</p>
<ul>
<li>電話・問い合わせフォームなどで相談、現地調査を依頼</li>
<li>現地調査(ひび割れの幅・タイルの浮き範囲・下地の状態を確認。多くの場合は無料)</li>
<li>工法・作業日数・費用を提示した見積書の受け取り</li>
<li>内容に納得できれば契約</li>
<li>施工</li>
<li>仕上がりの確認・支払い</li>
</ul>

<h2>見積もりを比較するときに見ておきたいポイント</h2>
<p>「外壁工事一式」のような大まかな表記の見積書は要注意です。㎡単価・使用材料のメーカー名や商品名・工法まで明記された詳細な見積もりを出す業者を選ぶことをおすすめします。3〜5社程度から話を聞き、次の点もあわせて確認しましょう。</p>
<ul>
<li>提案されている工法とその理由(症状に対してなぜその工法を選んだのか)</li>
<li>労災保険・損害賠償責任保険への加入状況</li>
<li>ロープアクセスを提案された場合、ロープ高所作業特別教育の修了者が在籍しているか</li>
<li>施工中の写真提出・進捗報告に対応してもらえるか(下地処理の甘さによる雨漏り事例を防ぐため)</li>
</ul>

<h2>保証について、契約書での確認が重要です</h2>
<p>国土交通省の資料によると、リフォーム工事において保証期間が契約書に明記されないケースは、戸建てで約22%、マンションで約44%にのぼるとされています。保証(契約不適合責任)は当事者間の合意で最長10年まで延長できますが、業者によって1〜10年と幅があり、経年劣化や天災による損傷は対象外となるのが一般的です。契約前に、保証期間と対象範囲を書面で確認しておきましょう。</p>

