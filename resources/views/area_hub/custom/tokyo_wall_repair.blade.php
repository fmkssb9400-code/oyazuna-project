<h2>よくある質問</h2>
<h3>Q. タイルが1〜2枚浮いているだけでも対応してもらえますか。</h3>
<p>A. 対応可能です。小規模なタイル交換であれば、工賃込みで20,000〜22,000円程度が目安とされています。ただし下地補修が絡む場合は、枚数が少なくても費用が上がることがあります。</p>
<h3>Q. 12条点検で指摘を受けたら、いつまでに補修すればよいですか。</h3>
<p>A. 指摘内容や自治体の判断によって異なるため、報告書を確認した建築士や特定建築物調査員、または補修業者に確認することをおすすめします。放置すると次回点検でも同じ指摘を受け続けることになります。</p>
<h3>Q. 補修と一緒に外壁塗装もしたほうがよいですか。</h3>
<p>A. 補修箇所と全体の劣化状況によります。部分補修だけで済む場合もあれば、全体の外壁塗装のタイミングと合わせたほうが効率的な場合もあるため、現地調査の際に業者に相談してみてください。</p>

<h2>まとめ</h2>
<p>東京都内の外壁補修は、12条点検をきっかけに発注するケースが典型的です。補助金は「使えるはず」という前提で予算を組まず、対象工事の範囲を事前に自治体窓口で確認しておくこと、そして見積書の内容(工法・単価の内訳・保証)を複数社で比較することが、後悔しない発注につながります。</p>
