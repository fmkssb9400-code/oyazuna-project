<h2>東京都で鳥害対策を検討している方へ</h2>
<p>「ビルの屋上や庇に鳩が住み着いて糞害に困っている」「近隣で餌やりをしている人がいて、いくら対策してもきりがない」。東京都内でビルやマンションを所有・管理していて、こうした悩みを抱えてはいませんか。</p>
<p>実は、東京都内の多くの区市では、公共の場所でのハトやカラスへの餌やりを禁止する条例が制定されています。ただし、その内容は区市によってかなり異なります。この記事では、その実態と、建物側でできる鳥害対策の考え方をまとめます。防鳥ネットの費用相場や業者選びのポイントについては、当サイトの別記事「<a href="/news/bird-control-cost">鳩対策・防鳥ネットの費用相場は？マンション・ビルの鳥害対策、業者選びのポイントも解説</a>」で詳しく解説しているので、あわせてご確認ください。</p>

<h2>東京都内の「餌やり禁止条例」、区によってかなり違います</h2>
<p>東京都全体を一律に規制する「餌やり禁止条例」があるわけではありません。各区市がそれぞれ独自に条例を制定しており、罰則の有無・金額も区市ごとに異なります。</p>
