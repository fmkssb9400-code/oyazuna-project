<h2>よくある質問</h2>
<h3>Q. 近隣で餌やりをしている人を見つけたらどうすればよいですか。</h3>
<p>A. まずは建物の所在地を管轄する区市の環境担当窓口に相談することをおすすめします。区市によっては指導・勧告の対象になる場合があります。ただし条例の有無・内容は区市ごとに異なるため、自分の建物がある区市の制度を確認してください。</p>
<h3>Q. 鳩を自分で捕獲してもよいですか。</h3>
<p>A. 鳥獣保護管理法により、野生の鳩を許可なく捕獲することはできません。対策は、巣を作らせない・寄り付かせないための防鳥ネットや忌避剤の設置が基本になります。</p>
<h3>Q. マンションの管理組合として対応する場合、何から始めればよいですか。</h3>
<p>A. まずは被害箇所の現地調査を業者に依頼し、対策方法と費用の見積もりを取ることから始めるとよいでしょう。理事会で検討する場合は、複数社の見積もりと対策内容を比較資料としてまとめておくと、合意形成がスムーズになります。</p>

<h2>まとめ</h2>
<p>東京都内の鳩・カラス対策は、区市ごとに異なる餌やり禁止条例という地域レベルの取り組みと、防鳥ネットなど建物側での直接対策の両輪で考える必要があります。悪質な餌やりに困っている場合は区市の窓口へ、建物自体の被害対策は専門業者への相談が現実的な進め方です。</p>
