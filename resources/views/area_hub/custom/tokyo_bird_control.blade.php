<p>このように、罰則がある区・ない区、金額もまちまちです。ビルの所在地によって適用される条例が異なるため、悪質な餌やり被害に困っている場合は、まず所在地の区市の環境担当窓口に相談することをおすすめします。</p>

<h2>なぜこうした条例が増えているのか</h2>
<p>背景には、都市部での鳥害に悩む住民・事業者の増加があります。大田区では、ある男性が駅前で大量の餌をまき続け、最大150羽ほどの鳩が集まって糞害・騒音・ネズミの発生といった被害が周辺の飲食店街に広がったことが、条例制定のきっかけになったと報じられています。餌やり自体を直接禁じる法律がないため、区が独自に条例で対処の根拠を作った、という経緯です。国立市のNPO法人「バードリサーチ」の調査によると、1990年代と比べて都心部のドバトは減少傾向にある一方、下町や郊外では増加傾向がみられ、条例による餌やり抑制の効果もあってか、生息分布が分散してきているとみられています。</p>

<h2>建物側でできる対策</h2>
<p>条例による餌やり抑制は地域全体の対策ですが、自分の建物を鳩の被害から守るには、防鳥ネットの設置など、建物側での直接的な対策が必要です。費用相場・業者選びのポイントについては、別記事「<a href="/news/bird-control-cost">鳩対策・防鳥ネットの費用相場は？マンション・ビルの鳥害対策、業者選びのポイントも解説</a>」で詳しく解説しています。ロープアクセスなどの無足場工法であれば、足場を組まずに高所のベランダ・庇・屋上への防鳥ネット設置が可能なケースもあるため、建物の形状に応じて業者に相談してみてください。</p>

