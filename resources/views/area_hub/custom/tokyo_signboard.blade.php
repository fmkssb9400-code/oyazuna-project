<h2>東京都で看板の設置・作業を検討している方へ</h2>
<p>「看板を新しく設置したいが、許可は必要なのか」「自社の看板が条例違反になっていないか心配」。東京都内で店舗やビルの看板を管理していて、こうした疑問を持ってはいませんか。</p>
<p>ラッコキーワードの調査でも「屋外広告物条例 東京都」という検索が月間590件と多く、「看板を勝手に設置してもいいですか?」「屋外に看板を設置するときの法律は?」といった質問も高い関心を集めています。この記事では、東京都屋外広告物条例の要点と、看板作業の業者選びのポイントをまとめます。</p>

<h2>東京都の屋外広告物条例、まず知っておきたいこと</h2>
<p>屋外広告物法という国の法律を根拠に、各都道府県・政令指定都市が独自の条例を定めており、東京都には「東京都屋外広告物条例」があります。看板や広告塔を掲出するには、この条例に従って許可を受ける必要があります(景観の保護・公衆への危害防止が目的です)。</p>
<div style="margin: 2em 0; padding: 16px 20px; background-color: #fff7ed; border: 2px solid #d97706;"><div style="display: inline-block; margin-bottom: 10px; padding: 4px 14px; background-color: #d97706; color: #ffffff; font-weight: bold;">誤解しやすいポイント</div><div>「東京都内ならどこでも同じ条例が適用される」わけではありません。八王子市と町田市は、東京都条例とは別に独自の屋外広告物条例を制定しており、許可基準・提出書類・申請窓口が異なります。また港区のように、東京都条例に加えて区独自の景観条例に基づく事前協議が必要になる自治体もあります。設置場所の市区町村がどの条例の対象になるかは、着工前に必ず窓口へ確認することをおすすめします。</div></div>

<h2>許可が必要なケース・不要なケース</h2>
<p>屋外広告物の種類・表示面積によって、許可の要否が変わります。壁面看板・袖看板(突出看板)・自立看板・野立て看板・屋上広告塔・懸垂幕などは基本的に許可の対象です。デジタルサイネージや窓ガラスサイン、のぼり旗は、条件によって許可が必要になる場合があります。比較的小規模な広告物には許可が不要になるケースもありますが、面積の基準は広告物の種類によって細かく分かれているため、「この看板は申請が必要か」を業者や窓口に確認してから進めることをおすすめします。</p>

<h2>禁止区域・禁止物件</h2>
<p>次のような区域・物件には、そもそも屋外広告物を表示できません。</p>
<ul>
<li>第一種・第二種低層住居専用地域、第一種・第二種中高層住居専用地域、田園住居地域</li>
<li>特別緑地保全地区、景観地区(旧美観地区)、風致地区</li>
<li>文化財保護法の建造物、社寺・教会、墓地・火葬場</li>
<li>学校、病院、公会堂、図書館、美術館、官公署等の建造物とその敷地</li>
<li>道路、鉄道の路線用地</li>
<li>橋、高架道路、道路標識、信号機、街路樹、郵便ポストなど</li>
</ul>
<p>自分の氏名・店名・商標を表示する「自家用広告物」については、禁止区域内でも一定の条件下で表示できる適用除外規定があります。詳細な条件は複雑なため、該当しそうな場合は窓口に確認することをおすすめします。</p>

