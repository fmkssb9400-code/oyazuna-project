<p>区長・市長・町長が許可する広告物は、区市町によって手数料が異なる場合があります。正確な金額は設置場所の屋外広告物取扱窓口で確認してください。なお、高さ4mを超える、または表示面積10㎡を超える広告塔・広告板を設置する場合は、屋外広告物管理者の資格証明の提出が必要です。</p>

<h2>違反した場合のリスク</h2>
<p>無許可で広告物を掲出した場合や、除却命令に従わなかった場合には、罰則が科される可能性があります。設置方法が危険なものや、道路交通の安全を阻害するものは違反広告物として、簡易除却(はり紙等)や措置命令の対象になることもあります。既存の看板についても、許可の更新を忘れると違反状態になってしまうため、許可期間の管理は重要です。設置後に必要な法定点検の周期や資格については、当サイトの別記事「<a href="/news/signboard-legal-inspection">看板の法定点検、義務はいつから？周期・資格・費用をわかりやすく解説</a>」もご確認ください。</p>

<h2>業者選びのポイント</h2>
<ul>
<li>許可申請の手続きに対応してもらえるか、または申請の要否を含めて相談に乗ってもらえるか</li>
<li>高さ4m超・表示面積10㎡超の広告塔・広告板の場合、屋外広告物管理者の資格を持つ担当者がいるか</li>
<li>電飾看板(LED看板)の配線作業を伴う場合、電気工事士の資格者が在籍しているか</li>
<li>労災保険・賠償責任保険に加入しているか</li>
<li>3社程度から見積もりを取り、施工内容と費用を比較したか</li>
</ul>

<h2>よくある質問</h2>
<h3>Q. 小さい看板なら許可はいらないと聞きましたが本当ですか。</h3>
<p>A. 広告物の種類や設置場所によっては、一定の面積以下であれば許可が不要になる場合があります。ただし基準は広告物の種類ごとに細かく定められているため、「これくらい小さいから大丈夫」と自己判断せず、業者や窓口に確認することをおすすめします。</p>
<h3>Q. 八王子市や町田市に店舗がある場合、東京都の条例を確認すればよいですか。</h3>
<p>A. いいえ、八王子市と町田市は東京都条例とは別に独自の条例を制定しているため、それぞれの市の条例・窓口を確認する必要があります。</p>
<h3>Q. 既存の看板が条例違反になっていないか不安です。どうすればよいですか。</h3>
<p>A. 看板の高さ・面積・設置場所の条例適合状況は、専門業者に現地確認を依頼することで把握できます。許可を受けている場合は、許可済シールが看板本体や店舗出入口に貼付されているはずなので、まずはその有無を確認するとよいでしょう。</p>

<h2>まとめ</h2>
<p>東京都内で看板を設置・維持するには、東京都屋外広告物条例(または八王子市・町田市の独自条例)に基づく許可と、区市町村ごとに異なる手続きへの理解が欠かせません。「東京都内だから同じルール」と思い込まず、設置場所の条例を確認したうえで、許可申請や資格者の在籍状況まで対応できる業者を選ぶことが、後々のトラブルを避けることにつながります。</p>
