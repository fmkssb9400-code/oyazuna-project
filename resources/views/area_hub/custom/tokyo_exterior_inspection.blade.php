<h2>東京都で外壁調査を検討している方へ</h2>
<p>「法定調査の時期が近づいているが、打診調査以外の方法もあると聞いた」「ドローンや赤外線での調査は本当に認められているのか」。東京都内でビルやマンションを所有・管理していて、こうした疑問を持ってはいませんか。</p>
<p>ラッコキーワードの調査でも、外壁調査に関する質問の中で「国土交通省はドローンによる外壁調査を認めていますか?」「赤外線による外壁調査の費用はいくらですか?」という2つの質問が、直近1か月で急浮上し最も検索されていることが分かりました。この記事では、この2つの疑問を中心に、調査手法の違いと費用相場、業者選びのポイントをまとめます。</p>

<h2>ドローン・赤外線調査は国に認められているのか</h2>
<p>結論として、認められています。2022年1月18日の告示改正(平成20年国土交通省告示第282号の一部改正)により、無人航空機(ドローン)による赤外線調査は「テストハンマーによる打診と同等以上の精度」を持つ調査方法として法的に位置づけられました。ただし、どんなドローン調査でもよいわけではなく、日本建築防災協会が策定した「定期報告制度における赤外線調査ガイドライン」に準拠していることが前提条件になります。調査を依頼する際は、業者がこのガイドラインに沿った調査を実施しているかを確認しておくと安心です。</p>

<h2>調査手法の違い</h2>
<ul>
<li><strong>打診法(接触法)</strong>：調査員が打診棒で外壁を叩き、打撃音の違いでタイルやモルタルの浮きを判別する、法定調査の基準的な手法です。人の感覚による精密な判定が可能な一方、足場・ロープアクセス・ゴンドラなど高所へのアクセス手段が必須で、コスト・工期がかかります。</li>
<li><strong>赤外線調査(非接触法)</strong>：赤外線カメラで外壁表面の温度分布を計測し、浮き・剥離部分を検出します。足場やゴンドラが不要なためコストを抑えやすく、反応箇所を面的・視覚的に把握しやすいのが特長です。一方で、日射条件・仕上げ材・浮きの厚さによって精度が変動し、浮きが薄い場合は判別が難しいこともあります。</li>
</ul>
<p>実務では、赤外線調査で建物全体を面的に把握したうえで、気になる箇所だけ打診で近接確認する、という併用が現実的な進め方とされています。建物の規模や形状によって適した組み合わせは変わるため、業者に相談して調査計画を立てることをおすすめします。</p>

