</ul>

<h2>業者選びのポイント</h2>
<p>外壁調査は法定調査としての性格上、誰でも実施・報告できるわけではありません。次の点を確認しておきましょう。</p>
<div style="margin: 2em 0; padding: 16px 20px; background-color: #f0fdf4; border: 2px solid #4ade80;"><div style="margin-bottom: 10px;"><span style="font-weight: bold; color: #166534;">✓ 東京都で業者を選ぶ際のチェックポイント</span></div><ul style="margin:0; padding-left:1.2em; color:#166534;"><li>調査員が一級・二級建築士、または「特定建築物調査員」の資格を持っているか</li><li>建物の条件に合わせて打診・赤外線を使い分ける提案力があるか</li><li>ドローンによる赤外線調査の場合、日本建築防災協会のガイドラインに準拠しているか</li><li>報告書が「浮き」「ひび」といった大まかな分類だけでなく、改修工事の判断材料になる具体性を持っているか</li><li>労災保険・賠償責任保険に加入しているか</li><li>3社程度から見積もりを取り、提案内容と費用を比較したか</li></ul></div>
<p>報告書の内容が大まかな分類にとどまり、その後の改修工事の判断材料にならなかったというトラブル事例も報告されています。契約前に、報告書のサンプルを見せてもらえるか確認しておくと安心です。</p>

<h2>こんな業者には要注意</h2>
<p>独立行政法人国民生活センターの発表によると、点検商法(業者が訪問して高額な工事をすすめる手口)の相談件数は2021年度7,435件、2022年度8,165件、2023年度12,510件と大きく増加しています。「無料点検します」といった訪問をきっかけに、必要以上の調査・工事を迫られるケースもあるため、次のようなサインに注意してください。</p>
<ul>
<li>調査員の資格(建築士・特定建築物調査員)を確認しても、資料で示さず曖昧に答える</li>
<li>その場で高額な改修工事の契約を迫ってくる</li>
<li>会社の所在地・固定電話番号・代表者名が公式サイトや見積書に記載されていない</li>
<li>見積書・契約書を書面(紙またはPDF)で発行しようとしない</li>
</ul>

<h2>よくある質問</h2>
<h3>Q. 赤外線調査だけで法定調査の要件を満たせますか。</h3>
<p>A. ドローンによる赤外線調査は、日本建築防災協会のガイドラインに準拠していれば、打診と同等以上の精度として認められています。ただし建物の状況によっては打診による近接確認が併用されることもあるため、業者に相談して調査方法を決めることをおすすめします。</p>
<h3>Q. マンションの外壁調査も義務の対象になりますか。</h3>
<p>A. 共同住宅を含む特定建築物は、用途・規模の要件を満たせば建築基準法12条の定期調査報告の対象になります。自分の建物が対象かどうかは、特定行政庁への確認や、建築士・特定建築物調査員への相談で判断できます。</p>
<h3>Q. 調査の結果、補修が必要と言われたらどうすればよいですか。</h3>
<p>A. 調査会社と補修工事の業者が別の場合は、複数の補修業者から見積もりを取って比較することをおすすめします。調査会社が補修工事も請け負う場合は、利害関係のない第三者にも意見を求めると、必要以上の工事を避けやすくなります。</p>

<h2>まとめ</h2>
<p>東京都内の外壁調査は、従来からの打診調査に加えて、赤外線調査やドローンによる赤外線調査という選択肢が法的にも認められています。それぞれのコスト・精度の特徴を理解したうえで、建物の状況に合った調査方法を業者に提案してもらうことが、無駄のない発注につながります。</p>
