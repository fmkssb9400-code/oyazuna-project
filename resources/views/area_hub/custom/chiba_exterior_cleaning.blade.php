<h2>建物のタイプ別に気をつけたいこと</h2>
<ul>
<li><strong>マンション</strong>：ベランダの利用が一時的に制限される時間帯や、住民への周知方法を業者と事前にすり合わせておく</li>
<li><strong>オフィスビル</strong>：営業を止めずに施工できるか、テナントへの告知タイミング</li>
<li><strong>工場・倉庫</strong>：京葉工業地域周辺では、油煙・粉じんによる汚れが局所的に集中しやすいため、汚れやすい面を重点的に洗浄する提案があるかを確認する</li>
</ul>

<h2>問い合わせから完了までの流れ</h2>
<ul>
<li>電話やフォームで相談、現地調査の依頼</li>
<li>現地調査(建物の高さ・立地・汚れの状態、屋上設備の有無をチェック。無料としている業者が多い)</li>
<li>見積書を受け取り、工法・作業日数・費用を確認</li>
<li>納得できれば契約、施工に進む</li>
<li>仕上がりの確認と支払い</li>
</ul>

<h2>相見積もりで確認したい観点</h2>
<p>1社だけで決めず、3〜5社程度に声をかけて比較することをおすすめします。金額に加えて、次のような点も見ておくと判断材料が増えます。</p>
<ul>
<li>㎡単価か一式料金か、内訳が明記されているか</li>
<li>沿岸部・工業地帯特有の汚れへの対応実績があるか</li>
<li>労災保険・損害賠償責任保険への加入状況</li>
<li>保証の有無と、仕上がりに不満があった場合の対応</li>
</ul>

