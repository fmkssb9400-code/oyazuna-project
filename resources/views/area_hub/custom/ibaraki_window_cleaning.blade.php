<h2>つくば・水戸・日立…茨城はいま変わりつつある</h2>
<p>2026年5月に公表された2025年国勢調査の速報値で、茨城県内の人口ランキングに大きな動きがありました。</p>
<p>つくば市が26万8,991人となり、県庁所在地である水戸市（26万5,773人）を上回って、県内最大の都市になったのです。水戸市が県内トップだったのは1980年以来45年間続いており、今回はそれを覆す歴史的な逆転でした（茨城県公式統計）。つくばエクスプレス沿線を中心に人口が増え続けており、増加数は全国の市町村でも4位という伸びです。オフィス需要・住宅需要ともに拡大が続いているとみられるエリアです。</p>
<p>一方、かつて日立製作所の企業城下町として栄えた日立市は15万8,763人で、前回調査から9.0%減少しました。茨城県全体でも人口は279万1,207人で、前回から2.6%減っています（茨城県公式統計）。都市によって人口動態が大きく異なるのが、いまの茨城県の特徴と言えそうです。</p>
<p>地理的には、日立市から鹿嶋市・神栖市にかけて太平洋に面した海岸線が続き、鹿嶋市・神栖市周辺には鹿島臨海工業地帯が広がっています。沿岸部の建物は潮風の影響を受けやすく、海岸から概ね2km以内の建物は月2回程度の清掃が目安となっています。</p>

