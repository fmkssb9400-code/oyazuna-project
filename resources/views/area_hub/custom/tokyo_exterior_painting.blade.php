<h2>東京都内の外壁塗装、補助金の実態</h2>
<p>東京都では23区の7割超、23区外でも7つの市で、外壁塗装や屋根塗装に関連した何らかの補助金制度があるとされています(複数の専門業者サイトの横断調査による)。外壁補修と違い、外壁塗装は「遮熱塗装」(日射反射率の高い塗料を使った塗装)という形で、省エネ目的の補助金対象に直接該当しやすいサービスです。</p>
