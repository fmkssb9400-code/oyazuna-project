<h2>発注の流れ</h2>
<p>初めて外壁塗装を発注する場合、流れが見えないと不安に感じるものです。業者による違いはありますが、おおむね次のように進みます。</p>
<ul>
<li>電話・問い合わせフォームなどで相談、現地調査を依頼</li>
<li>現地調査(建物の高さ・立地・劣化状況の確認。多くの場合は無料)</li>
<li>工法(ロープアクセス・ゴンドラ・足場)・塗料グレード・作業日数・費用を提示した見積書の受け取り</li>
<li>補助金を利用する場合は、契約・着工前に自治体への事前申込(この順番を間違えると対象外になることが多いため要注意)</li>
<li>内容に納得できれば契約、施工</li>
<li>仕上がりの確認・支払い</li>
</ul>

<h2>見積もりを比較するときに見ておきたいポイント</h2>
<p>1社の見積もりだけで即決せず、3〜5社程度から話を聞いて比較することをおすすめします。金額だけでなく、次の点も確認しておくと判断材料が増えます。</p>
<ul>
<li>単価の内訳(㎡単価・塗料のグレード・足場代・諸経費)が明記されているか</li>
<li>提案されている工法(ロープアクセス・ゴンドラ・足場)とその理由</li>
<li>補助金の対象となる塗料・工事内容かどうかを把握しているか</li>
<li>労災保険・損害賠償責任保険への加入状況</li>
<li>保証期間・保証の対象範囲(色あせのみか、剥がれ・ひび割れも含むか)</li>
</ul>

