    public function show(Request $request, string $slug)
    {
        abort_unless(isset($this->pages[$slug]), 404);

        $config = $this->pages[$slug];

        $baseQuery = function () use ($config): Builder {
            return Company::published()
                ->withCount('reviews')
                ->withAvg('reviews as average_rating', 'total_score')
                ->where(function (Builder $query) use ($config) {
                    $query->whereJsonContains('areas', $config['prefecture']);
                    foreach ($config['aliases'] ?? [] as $alias) {
                        $query->orWhereJsonContains('areas', $alias);
                    }
                })
                ->orderByDesc('recommend_score');
        };

        // 比較表用：上位10社のみ（一覧とは別に取得。ページングの影響を受けない）
        $topCompanies = $baseQuery()->take(10)->get();

        $companies = $baseQuery()
            ->paginate(10)
            ->withQueryString();

        return view('area.show', [
            'config' => $config,
            'slug' => $slug,
            'topCompanies' => $topCompanies,
            'companies' => $companies,
            'otherAreas' => collect($this->pages)->except($slug),
        ]);
    }
