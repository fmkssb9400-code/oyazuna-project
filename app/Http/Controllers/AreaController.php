                    foreach ($config['aliases'] ?? [] as $alias) {
                        $query->orWhereJsonContains('areas', $alias);
                    }
                })
                ->orderByDesc('recommend_score');
        };

        // 比較表用：上位10社のみ（一覧とは別に取得。ページングの影響を受けない）
        $topCompanies = $baseQuery()->take(10)->get();

        $companies = $baseQuery()
            ->paginate(10)
            ->withQueryString();

        return view('area.show', [
            'config' => $config,
            'slug' => $slug,
            'topCompanies' => $topCompanies,
            'companies' => $companies,
            'otherAreas' => collect($this->pages)->except($slug),
            'hubCategoryPages' => $allHubs->where('type', 'category'),
            'hubConditionPages' => $allHubs->where('type', 'condition'),
        ]);
    }
