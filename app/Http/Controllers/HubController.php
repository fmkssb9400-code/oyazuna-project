    public function category(Request $request, string $slug)
    {
        abort_unless(isset($this->pages[$slug]), 404);

        $config = $this->pages[$slug];

        $baseQuery = function () use ($config): Builder {
            $query = Company::published()
                ->withCount('reviews')
                ->withAvg('reviews as average_rating', 'total_score')
                ->orderByDesc('recommend_score');

            if ($config['type'] === 'condition') {
                $query->where('strength_tags', 'like', '%' . $config['tag'] . '%');
            } else {
                $query->whereJsonContains('service_categories', $config['key']);
            }

            return $query;
        };

        // 比較表用：上位10社のみ（一覧とは別に取得。ページングの影響を受けない）
        $topCompanies = $baseQuery()->take(10)->get();

        $companies = $baseQuery()
            ->paginate(12)
            ->withQueryString();

        return view('hub.category', [
            'config' => $config,
            'slug' => $slug,
            'topCompanies' => $topCompanies,
            'companies' => $companies,
            'otherHubs' => collect($this->pages)->except($slug),
        ]);
    }
